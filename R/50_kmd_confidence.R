# =============================================================================
# KMD STAGE — Kendrick mass defect confidence assessment and final plots
# -----------------------------------------------------------------------------
# PURPOSE
#   Provide an evidence stream that is independent of both spectral matching and
#   isotope-pattern detection: homologous-series membership.
#
#   Compounds belonging to the same homologous series (differing only by a
#   repeating unit) share a Kendrick mass defect. Plotting KMD against Kendrick
#   mass therefore places members of a series on a common line. Fitting that
#   line to authentic halogenated PAC standards gives a quantitative expectation
#   against which unknown compounds can be tested.
#
#   Three series are used because each is sensitive to a different structural
#   feature:
#     CH2  (14 Da)  alkylation / carbon-chain homology
#     H/Cl (34 Da)  chlorine-for-hydrogen substitution
#     Br2 (158 Da)  bromine substitution
#
#   An unknown that falls inside the 95% prediction interval of ALL THREE series
#   is far better supported than one satisfying a single series. A prediction
#   interval (not a confidence interval) is used because each sample compound is
#   a new individual observation, not an estimate of the mean.
#
# WHY THE TRAINING STANDARDS DO NOT USE WF2'S OWN CLASSIFICATION
#
#   For an unknown compound in a real sample, WF2's isotope-pattern guess is the
#   only evidence available, so its output is what gets tested against these
#   models. But the compounds used to TRAIN the models are not unknowns —
#   their identity is already known with certainty, because they are the
#   authentic standards that make up this mixture. Using WF2's guess to decide
#   which class a training standard belongs to is unnecessary and, when WF2's
#   guess is wrong, actively harmful: it trains the model on a mislabelled
#   example instead of on the ground truth already available.
#
#   This happened in practice. WF2's own classification of 1,6-Br2-Pyr placed
#   it in the mono_Cl group rather than di_Br, purely as an artefact of which
#   isotope peaks the algorithm happened to pair together — not because the
#   compound's true identity was ever in doubt. Several other di-halogenated
#   standards were affected the same way.
#
#   Training standards are therefore classified from data_wf2/
#   std_check_ground_truth_halo_class.csv, in which halogen_class has been
#   manually verified against each compound's known molecular formula, rather
#   than from WF2's own algorithmic output. This file is checked automatically
#   against the reference library by validate_standards_ground_truth() in
#   02_validate_libraries.R before it is used, so a mis-entered class is
#   caught rather than silently trained on. Real, unknown sample compounds
#   continue to be classified by WF2 exactly as before — ground truth is not
#   available for those, so WF2's isotope-pattern evidence is the correct and
#   only tool for them.
#
# TWO STAGES, TWO ENTRY POINTS
#
#   build_kmd_models()  fits the 12 regression models from the training data
#                        (see kmd_training_source in 00_setup.R) and saves a
#                        standalone diagnostic figure per series showing the
#                        fitted lines and the training standards ONLY, with no
#                        sample data at all. This runs once, is independent of
#                        any sample_name, and lets the models be inspected on
#                        their own before they are ever applied to real data --
#                        mirroring the "standards" output of the original
#                        standalone KMD project this pipeline consolidates.
#
#   run_kmd(sample_name) tests one sample's WF2 output against those models
#                        and saves the sample-specific figures. If called
#                        without a pre-built `models` argument it builds them
#                        itself first, so it remains fully usable on its own
#                        (e.g. when this file is knitted standalone).
#
# INPUT   data_wf2/std_check_ground_truth_halo_class.csv  (training standards,
#           halogen_class manually verified against known compound identity)
#         data_wf2/possible_halo_pacs2.csv  (theoretical training data, used
#           when kmd_training_source == "combined")
#         results_wf2/<sample>_all_halo_pacs.csv   (all halogen-positive peaks)
#         results_wf2/<sample>_halo_pacs.csv       (reference-matched subset)
# OUTPUT  kmd_final/standards_kmd_HCl.png   } model-only diagnostic plots,
#         kmd_final/standards_kmd_Br2.png   } generated once by
#         kmd_final/standards_kmd_CH2.png   } build_kmd_models()
#         kmd_final/<sample>_kmd_HCl.png    } sample-specific plots,
#         kmd_final/<sample>_kmd_Br2.png    } generated by
#         kmd_final/<sample>_kmd_CH2.png    } run_kmd(sample_name)
#         results_wf4/<sample>_kmd_ci_support.csv
# =============================================================================

# -----------------------------------------------------------------------------
# load_theoretical_kmd_training() — additional KMD regression training data
# from the theoretical halo-PAC reference library.
# -----------------------------------------------------------------------------
# WHY THEORETICAL DATA IS VALID TRAINING DATA HERE
#
# Kendrick mass and Kendrick mass defect are both deterministic functions of
# mass alone (KM = mass * nominal/exact; KMD = round(KM) - KM). Neither
# depends on how that mass was obtained. A regression of "where a halogen
# class sits in KMD space" is therefore a model of chemistry -- how the H:C
# ratio trends with molecular size within a class -- not of measurement, and
# there is no principled reason to restrict training data to the handful of
# authentic standards per class when up to 25 theoretical examples per class
# are available from the same reference table WF2 already uses for exact-mass
# matching (data_wf2/possible_halo_pacs2.csv).
#
# This was checked empirically before being adopted, not assumed. Fitting
# each class from theory-only and from standards-only data separately gave
# closely matching slopes and comparable residual scatter for three of the
# four classes (mono_Cl, di_Cl, mono_Br); real measurement noise, which
# theoretical masses cannot capture, was checked for directly and found not
# to be the dominant source of scatter in any of them. The fourth class
# (di_Br) showed an apparent slope disagreement that turned out to be
# small-sample instability, not a real conflict: the theoretical slope fell
# well inside the standards-only slope's own 95% confidence interval, and
# combining the two reduced the standard error of the fitted slope by 85%.
#
# Classification is by FORMULA (counting Cl and Br atoms directly), never by
# matching substrings in the compound name. A name-based check was tried
# first and rejected: it incorrectly filed mixed-halogen entries such as
# "Indole-Mono-Cl-Di-Br" under mono_Cl, which is not a mono-Cl compound.
load_theoretical_kmd_training <- function() {
  path <- file.path(dir_data$wf2, "possible_halo_pacs2.csv")
  if (!file.exists(path)) {
    warning("Theoretical halo-PAC library not found; KMD models will use ",
            "empirical standards only: ", path)
    return(NULL)
  }

  lib <- clean_names(read_csv(path, show_col_types = FALSE))

  # Vectorised element-count extraction: "Cl2" -> 2, "Cl" (no digit) -> 1,
  # absent -> 0. Applied to the whole formula column at once.
  cl_match <- str_match(lib$formula, "Cl(\\d*)")[, 2]
  br_match <- str_match(lib$formula, "Br(\\d*)")[, 2]
  n_cl <- ifelse(is.na(cl_match), 0L, ifelse(cl_match == "", 1L, as.integer(cl_match)))
  n_br <- ifelse(is.na(br_match), 0L, ifelse(br_match == "", 1L, as.integer(br_match)))

  lib %>%
    mutate(
      n_cl = n_cl, n_br = n_br,
      primary_class = case_when(
        n_cl == 1 & n_br == 0 ~ "mono_Cl",
        n_cl == 2 & n_br == 0 ~ "di_Cl",
        n_br == 1 & n_cl == 0 ~ "mono_Br",
        n_br == 2 & n_cl == 0 ~ "di_Br",
        TRUE ~ NA_character_
      ),
      name = possible_compounds,
      source = "theoretical"
    ) %>%
    filter(!is.na(primary_class)) %>%
    add_kmd("exact_mass") %>%
    select(name, primary_class, exact_mass, source,
           km_CH2, kmd_CH2, km_Cl, kmd_Cl, km_Br2, kmd_Br2)
}


# -----------------------------------------------------------------------------
# prep_kmd_df() — shared preparation used for BOTH the training standards and a
# sample's WF2 output: extracts exact_mass, derives primary_class, computes
# Kendrick mass/defect for all three series. See the header comment above for
# why exact_mass prefers corrected_exact_mass (present only for training
# standards) over the raw isotope-peak string.
# -----------------------------------------------------------------------------
EXCLUDE_FLAG <- "EXCLUDE_NO_MOLECULAR_ION"

prep_kmd_df <- function(df) {
  has_corrected <- "corrected_exact_mass" %in% names(df)

  if (has_corrected) {
    n_excluded <- sum(df$corrected_exact_mass == EXCLUDE_FLAG, na.rm = TRUE)
    if (n_excluded > 0) {
      message(sprintf(
        "  Excluding %d standard(s) with no observable molecular ion: %s",
        n_excluded,
        paste(df$name[df$corrected_exact_mass == EXCLUDE_FLAG], collapse = ", ")))
    }
    df <- df %>% filter(is.na(corrected_exact_mass) | corrected_exact_mass != EXCLUDE_FLAG)
  }

  df %>%
    mutate(
      exact_mass = if (has_corrected) {
        # Use the verified mass wherever supplied; fall back to the old
        # peak-string extraction only for rows where it is genuinely blank
        # (should not occur in the ground-truth file, but keeps this
        # function safe if the column is ever partially populated).
        coalesce(suppressWarnings(as.numeric(corrected_exact_mass)),
                map_dbl(detected_isotope_peaks, extract_mono_peak))
      } else {
        map_dbl(detected_isotope_peaks, extract_mono_peak)
      },
      primary_class = str_trim(str_extract(halogen_class, "^[^;]+"))
    ) %>%
    filter(!is.na(exact_mass), is.finite(exact_mass)) %>%
    add_kmd("exact_mass")
}


# -----------------------------------------------------------------------------
# plot_kmd_series() — build and save one KMD figure for one series.
#
# Used twice:
#   - by build_kmd_models(), with known_pts/unknown_pts left NULL, to save a
#     "standards"-only diagnostic plot showing just the fitted lines and the
#     training data, generated once and before any sample is processed;
#   - by run_kmd(), with the real known/unknown compounds supplied, to save
#     the sample-specific plot.
#
# Keeping this in one function guarantees the two are visually identical in
# every respect (theme, colours, ribbon style, point styling) except for
# which sample points, if any, are overlaid on top of the same fitted models.
# -----------------------------------------------------------------------------
plot_kmd_series <- function(ser, all_models, std, theoretical,
                            known_pts = NULL, unknown_pts = NULL,
                            title_prefix, extra_subtitle = "") {

  std_pts <- std %>%
    filter(primary_class %in% target_classes) %>%
    transmute(name, label = name,
              km  = .data[[paste0("km_",  ser)]],
              kmd = .data[[paste0("kmd_", ser)]],
              halogen_class = primary_class) %>%
    filter(!is.na(km), !is.na(kmd))

  # Theoretical points contributing to the fitted lines, shown as a faint,
  # unlabelled backdrop so the reader can see the evidence base behind each
  # regression line without the plot being overwhelmed by ~25 labels per
  # class. These are visually subordinate to the real standards (grey
  # triangles) and real sample data (colour-filled/open circles), which
  # remain the prominent, labelled markers.
  theory_pts <- if (!is.null(theoretical)) {
    theoretical %>%
      filter(primary_class %in% target_classes) %>%
      transmute(km  = .data[[paste0("km_",  ser)]],
                kmd = .data[[paste0("kmd_", ser)]],
                halogen_class = primary_class) %>%
      filter(!is.na(km), !is.na(kmd))
  } else {
    tibble(km = numeric(), kmd = numeric(), halogen_class = character())
  }

  build_ribbon <- function(mi, km_vals) {
    km_seq <- seq(min(km_vals, na.rm = TRUE), max(km_vals, na.rm = TRUE),
                  length.out = 300)
    pi <- predict(mi$model, newdata = data.frame(km = km_seq),
                  interval = "prediction", level = 0.95)
    tibble(km = km_seq, fit = pi[, "fit"], lwr = pi[, "lwr"], upr = pi[, "upr"],
           halogen_class = mi$class)
  }

  ser_models <- keep(all_models, ~ .x$series == ser)
  if (length(ser_models) == 0) return(invisible(NULL))

  known_km   <- if (!is.null(known_pts))   known_pts$km   else numeric()
  unknown_km <- if (!is.null(unknown_pts)) unknown_pts$km else numeric()
  all_km <- c(std_pts$km, theory_pts$km, known_km, unknown_km)
  ribbon <- map_dfr(ser_models, build_ribbon, km_vals = all_km)

  p <- ggplot() +
    geom_ribbon(data = ribbon,
                aes(x = km, ymin = lwr, ymax = upr, fill = halogen_class),
                alpha = 0.12, show.legend = FALSE) +
    geom_line(data = ribbon, aes(x = km, y = fit, colour = halogen_class),
              linewidth = 0.8, linetype = "dashed") +
    geom_point(data = theory_pts, aes(x = km, y = kmd, colour = halogen_class),
               size = 0.9, alpha = 0.25, shape = 16, show.legend = FALSE) +
    geom_point(data = std_pts, aes(x = km, y = kmd),
               colour = "grey55", size = 2, shape = 17, alpha = 0.7)

  if (!is.null(known_pts) && nrow(known_pts) > 0) {
    p <- p +
      geom_point(data = known_pts, aes(x = km, y = kmd, colour = halogen_class),
                 size = 3, shape = 16) +
      geom_text_repel(data = known_pts,
                      aes(x = km, y = kmd, label = label, colour = halogen_class),
                      size = 2.8, max.overlaps = 30, show.legend = FALSE)
  }
  if (!is.null(unknown_pts) && nrow(unknown_pts) > 0) {
    p <- p +
      geom_point(data = unknown_pts, aes(x = km, y = kmd, colour = halogen_class),
                 size = 3, shape = 1, stroke = 1.1) +
      geom_text_repel(data = unknown_pts,
                      aes(x = km, y = kmd, label = label, colour = halogen_class),
                      size = 2.5, fontface = "italic",
                      max.overlaps = 30, show.legend = FALSE)
  }

  n_known   <- if (!is.null(known_pts))   nrow(known_pts)   else 0L
  n_unknown <- if (!is.null(unknown_pts)) nrow(unknown_pts) else 0L

  p <- p +
    scale_colour_manual(values = class_colours, name = "Halogen class") +
    scale_fill_manual(values = class_colours) +
    labs(title = sprintf("%s - %s series", title_prefix, ser),
         subtitle = sprintf(
           "Filled = reference-matched | Open = unmatched | Grey triangles = standards | Faint dots = theoretical training (n_known=%d, n_unknown=%d, n_theoretical=%d)%s",
           n_known, n_unknown, nrow(theory_pts), extra_subtitle),
         x = kmd_series[[ser]]$label,
         y = sprintf("KMD (%s)", ser)) +
    theme_bw(base_size = 11) +
    theme(legend.position = "bottom", plot.subtitle = element_text(size = 8))

  fname <- file.path(dir_kmd, sprintf("%s_kmd_%s.png", title_prefix,
                                      ifelse(ser == "Cl", "HCl", ser)))
  ggsave(fname, p, width = 8, height = 6, dpi = 300, bg = "white")
  message("  Saved plot: ", basename(fname))
  invisible(p)
}


# =============================================================================
# build_kmd_models() — fit the 12 KMD regression models and save the
# standards-only diagnostic plots. Independent of any sample_name; run this
# once before processing any sample data through run_kmd().
# =============================================================================
build_kmd_models <- function(
    standards_file = file.path(dir_data$wf2, "std_check_ground_truth_halo_class.csv")) {

  message("\n=== KMD MODELS : fitting from training data ===")

  if (!file.exists(standards_file)) {
    warning("KMD: standards file not found - model building skipped: ", standards_file)
    return(invisible(NULL))
  }

  # Catch a mis-entered ground-truth class before it silently trains a model.
  # This is exactly the check that found "5,6-Br2-1,2-H2-Acy" incorrectly
  # entered as poly_or_mixed (its formula, C12H8Br2, is unambiguously di_Br)
  # during manual preparation of this file -- it now runs automatically.
  validate_standards_ground_truth(standards_file)

  std <- clean_names(read_csv(standards_file, show_col_types = FALSE)) %>% prep_kmd_df()
  message(sprintf("  Empirical training standards : %d", nrow(std)))

  message(sprintf("  KMD training source: %s", kmd_training_source))
  theoretical <- if (identical(kmd_training_source, "combined")) {
    load_theoretical_kmd_training()
  } else {
    NULL
  }
  if (!is.null(theoretical)) {
    message(sprintf("  Theoretical training compounds: %d", nrow(theoretical)))
  }

  # Model-fitting training set = empirical standards + theoretical library.
  # Only the columns needed for fitting are kept from each source, so the
  # differing column sets (std carries retention time, isotope evidence etc.;
  # theoretical carries none of that) combine cleanly.
  fit_cols <- c("name", "primary_class", "km_CH2", "kmd_CH2",
               "km_Cl", "kmd_Cl", "km_Br2", "kmd_Br2")
  training_data <- bind_rows(
    std %>% select(any_of(fit_cols)) %>% mutate(source = "empirical"),
    if (!is.null(theoretical)) theoretical %>% select(any_of(c(fit_cols, "source")))
    else tibble()
  )
  message(sprintf("  Combined training set for model fitting: %d compounds", nrow(training_data)))

  # ---- Fit lm(kmd ~ km) per series x halogen class -------------------------
  # At least three points are required for a meaningful line; combinations with
  # fewer are skipped rather than fitted unreliably.
  all_models <- list()
  for (ser in names(kmd_series)) {
    for (cls in target_classes) {
      train <- training_data %>%
        filter(primary_class == cls) %>%
        transmute(name,
                  km  = .data[[paste0("km_",  ser)]],
                  kmd = .data[[paste0("kmd_", ser)]]) %>%
        filter(!is.na(km), !is.na(kmd))
      if (nrow(train) < 3) next
      mod <- lm(kmd ~ km, data = train)
      all_models[[paste(ser, cls, sep = "_")]] <- list(
        series = ser, class = cls,
        km_col = paste0("km_", ser), kmd_col = paste0("kmd_", ser),
        model = mod, r2 = summary(mod)$r.squared,
        n_train = nrow(train), km_range = range(train$km)
      )
      message(sprintf("    %-4s / %-8s  r2=%.4f  n=%d", ser, cls,
                      summary(mod)$r.squared, nrow(train)))
    }
  }
  if (length(all_models) == 0) {
    warning("KMD: no models could be fitted - stage skipped.")
    return(invisible(NULL))
  }

  # ---- Save the standards-only diagnostic plots, one per series -----------
  # Generated ONCE, independent of any sample, so the fitted models can be
  # inspected on their own before being applied to real data. Mirrors the
  # "standards" output of the original standalone KMD project.
  message("  Saving standards-only diagnostic plots (kmd_final/standards_kmd_*.png)")
  for (ser in names(kmd_series)) {
    plot_kmd_series(ser, all_models, std, theoretical,
                    known_pts = NULL, unknown_pts = NULL,
                    title_prefix = "standards",
                    extra_subtitle = " | model-only, no sample data")
  }

  invisible(list(all_models = all_models, std = std, theoretical = theoretical))
}


# =============================================================================
# run_kmd() — test one sample's WF2 output against the fitted KMD models and
# save the sample-specific plots. If `models` is not supplied, builds them
# first by calling build_kmd_models(), so this remains fully usable on its
# own (e.g. when this file is knitted standalone).
# =============================================================================
run_kmd <- function(sample_name, models = NULL,
                    standards_file = file.path(dir_data$wf2,
                                               "std_check_ground_truth_halo_class.csv")) {

  message("\n=== KMD STAGE : homologous-series confidence ===")

  if (is.null(models)) {
    models <- build_kmd_models(standards_file)
  }
  if (is.null(models)) {
    warning("KMD: no models available - stage skipped.")
    return(invisible(NULL))
  }
  all_models  <- models$all_models
  std         <- models$std
  theoretical <- models$theoretical

  # ---- Load sample peaks and split known vs unknown ------------------------
  # known   = matched to the halo-PAC reference table by WF2
  # unknown = passed the isotope filter but had no reference match. These are
  #           the genuine non-targeted discoveries, and are exactly what the
  #           KMD test is most useful for.
  p_all <- file.path(dir_res$wf2, paste0(sample_name, "_all_halo_pacs.csv"))
  p_lib <- file.path(dir_res$wf2, paste0(sample_name, "_halo_pacs.csv"))
  if (!file.exists(p_all) || !file.exists(p_lib)) {
    warning("KMD: WF2 outputs not found - stage skipped.")
    return(invisible(NULL))
  }

  samp_all <- clean_names(read_csv(p_all, show_col_types = FALSE)) %>% prep_kmd_df()
  samp_lib <- clean_names(read_csv(p_lib, show_col_types = FALSE)) %>% prep_kmd_df()

  # ---- Apply verified ground truth to any sample peak that IS a standard --
  #
  # samp_all/samp_lib above come from WF2's fresh, unmodified run on THIS
  # sample_name -- the same algorithmic classification whose errors motivated
  # building the ground-truth file in the first place (see the header
  # comment). The training models fitted in build_kmd_models() already use
  # verified labels correctly. Without this step, however, that correction
  # stops at the model: any sample peak sharing a name with a known standard
  # -- which is every peak, when sample_name IS the standards run itself, as
  # when sample_name = "std_check" -- would still be plotted and reported
  # under WF2's own guess rather than the verified identity.
  #
  # This was caught by comparing this project's output against a manual
  # standalone run using the same corrected ground-truth file: the fitted
  # regression lines matched exactly (confirming the modelling itself is
  # correct), but 7 of the 28 standards were plotted under the wrong class --
  # exactly the compounds whose WF2 guess and verified identity disagree.
  #
  # The fix: wherever a sample peak's name matches a ground-truth standard,
  # its primary_class is overridden with the verified value. A real,
  # genuinely unknown compound from a fish or sediment sample will not match
  # any name in the standards file and is classified by WF2 exactly as
  # before -- ground truth is not available for it, so WF2's isotope-pattern
  # evidence remains the correct and only tool.
  gt_lookup <- setNames(std$primary_class, std$name)

  apply_ground_truth <- function(df) {
    df %>%
      mutate(primary_class = if_else(name %in% names(gt_lookup),
                                     unname(gt_lookup[name]),
                                     primary_class))
  }

  samp_all <- apply_ground_truth(samp_all)
  samp_lib <- apply_ground_truth(samp_lib)

  kmd_known   <- samp_lib
  kmd_unknown <- samp_all %>% anti_join(samp_lib, by = c("name", "rt1_s", "rt2_s"))
  message(sprintf("  Known (matched)    : %d", nrow(kmd_known)))
  message(sprintf("  Unknown (unmatched): %d", nrow(kmd_unknown)))

  test_set <- bind_rows(
    kmd_known   %>% mutate(compound_type = "known"),
    kmd_unknown %>% mutate(compound_type = "unknown", possible_halo_pac = NA_character_)
  )

  # ---- Test each compound against every fitted model -----------------------
  check_compound <- function(row, mi) {
    km_val  <- row[[mi$km_col]]
    kmd_val <- row[[mi$kmd_col]]
    if (is.na(km_val) || is.na(kmd_val)) return(NULL)
    pi <- predict(mi$model, newdata = data.frame(km = km_val),
                  interval = "prediction", level = 0.95)
    tibble(
      name = row$name, series = mi$series, tested_class = mi$class,
      km = round(km_val, 4), kmd_observed = round(kmd_val, 4),
      kmd_predicted = round(pi[1, "fit"], 4),
      pi_lower = round(pi[1, "lwr"], 4), pi_upper = round(pi[1, "upr"], 4),
      in_band  = kmd_val >= pi[1, "lwr"] & kmd_val <= pi[1, "upr"],
      # flags compounds beyond the mass range covered by the standards, where
      # the regression is extrapolating and is correspondingly less reliable
      extrapolated = km_val < mi$km_range[1] | km_val > mi$km_range[2],
      model_r2 = round(mi$r2, 3)
    )
  }

  ci_results <- map_dfr(seq_len(nrow(test_set)), function(i)
    map_dfr(all_models, ~ check_compound(test_set[i, ], .x)))

  # ---- Summarise to one row per compound ------------------------------------
  # Confidence reflects how many of the three independent series agree.
  ci_summary <- ci_results %>%
    group_by(name, tested_class) %>%
    summarise(series_in_band      = sum(in_band),
              series_tested       = n(),
              series_extrapolated = sum(extrapolated),
              mean_r2             = round(mean(model_r2), 3),
              .groups = "drop") %>%
    mutate(kmd_confidence = case_when(
      series_in_band == 3 ~ "High - all 3 series within 95% PI",
      series_in_band == 2 ~ "Moderate - 2/3 series within PI",
      series_in_band == 1 ~ "Low - 1/3 series within PI",
      TRUE                ~ "Not supported by KMD"),
      extrapolation_flag = if_else(series_extrapolated > 0,
                                   "EXTRAPOLATED - outside standards KM range",
                                   NA_character_))

  best_per_compound <- ci_summary %>%
    group_by(name) %>% slice_max(series_in_band, n = 1, with_ties = FALSE) %>%
    ungroup() %>% rename(kmd_supported_class = tested_class)

  kmd_ci_output <- test_set %>%
    left_join(best_per_compound %>%
                select(name, kmd_supported_class, series_in_band,
                       kmd_confidence, extrapolation_flag, mean_r2),
              by = "name") %>%
    mutate(kmd_supported_class = coalesce(kmd_supported_class, primary_class)) %>%
    arrange(rt1_s, rt2_s)

  out_csv <- file.path(dir_res$wf4, paste0(sample_name, "_kmd_ci_support.csv"))
  write_csv(kmd_ci_output, out_csv)
  message("  Saved: ", basename(out_csv))
  print(count(kmd_ci_output, kmd_confidence, name = "n"))

  # ---- Build the three sample-specific plots --------------------------------
  # One figure per series, each showing all four halogen classes together with
  # their regression lines and 95% prediction bands:
  #   grey triangles = training standards      faint dots = theoretical training
  #   filled circles = reference-matched sample peaks
  #   open circles   = unmatched peaks (non-targeted discoveries)
  prep_pts <- function(df, ser, is_known) {
    if (nrow(df) == 0) return(NULL)
    df %>%
      transmute(name,
                km  = .data[[paste0("km_",  ser)]],
                kmd = .data[[paste0("kmd_", ser)]],
                halogen_class = primary_class,
                possible_halo_pac = if ("possible_halo_pac" %in% names(df))
                  possible_halo_pac else NA_character_) %>%
      filter(!is.na(km), !is.na(kmd), halogen_class %in% target_classes) %>%
      mutate(label = if (is_known)
        if_else(!is.na(possible_halo_pac) & possible_halo_pac != "",
                possible_halo_pac, name) else name)
  }

  for (ser in names(kmd_series)) {
    known_pts   <- prep_pts(kmd_known,   ser, TRUE)
    unknown_pts <- prep_pts(kmd_unknown, ser, FALSE)
    plot_kmd_series(ser, all_models, std, theoretical,
                    known_pts = known_pts, unknown_pts = unknown_pts,
                    title_prefix = sample_name)
  }

  invisible(kmd_ci_output)
}
